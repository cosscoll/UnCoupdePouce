"""Compatibility for UCP's existing SQL on a private PostgreSQL schema.

SQLite remains the local default. PostgreSQL uses session/direct connections,
not a transaction pooler (search_path is session state). No browser DB access.
"""
from contextlib import contextmanager
import re
import sqlite3
import os
import socket
import logging
import psycopg
from psycopg import sql
from psycopg.pq import TransactionStatus

IDENTITY_TABLES = {
    'users', 'projects', 'applications', 'messages', 'beta_interest', 'audit',
    'notifications', 'enterprise_accounts', 'enterprise_artisans', 'drafts',
    'photos', 'reports', 'admin_decisions', 'support_tickets',
}

class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

def row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))

class Result:
    def __init__(self, rows=(), rowcount=0, lastrowid=None):
        self.rows = list(rows)
        self.rowcount, self.lastrowid = rowcount, lastrowid
    def fetchone(self):
        return self.rows.pop(0) if self.rows else None
    def fetchall(self):
        rows, self.rows = self.rows, []
        return rows
    def __iter__(self):
        return iter(self.fetchall())


def translate(query):
    """Translate only dialect constructs used by the existing, tested UCP SQL."""
    query = query.strip().rstrip(';')
    query = re.sub(r'\bBLOB\b', 'BYTEA', query, flags=re.I)
    query = re.sub(r'\bINTEGER PRIMARY KEY\b',
                   'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', query, flags=re.I)
    query = re.sub(r'\bORDER BY rowid\b', 'ORDER BY id', query, flags=re.I)
    if re.match(r'INSERT OR IGNORE\b', query, re.I):
        query = re.sub(r'INSERT OR IGNORE', 'INSERT', query, count=1, flags=re.I)
        query += ' ON CONFLICT DO NOTHING'
    # SQL literals must retain question marks / percent characters unchanged.
    pieces = re.split(r"('(?:[^']|'')*')", query)
    return ''.join(p.replace('?', '%s') if i % 2 == 0 else p
                   for i, p in enumerate(pieces))


class Connection:
    def __init__(self, url, schema):
        if not re.fullmatch(r'ucp_[a-z0-9_]{1,45}', schema):
            raise ValueError('Use a private ucp_ schema')
        self.schema = schema
        options = {}
        if os.getenv('VERCEL') == '1':
            info = psycopg.conninfo.conninfo_to_dict(url)
            try:
                addresses = socket.getaddrinfo(info['host'], int(info.get('port',5432)),
                                               socket.AF_INET, socket.SOCK_STREAM)
                options['hostaddr'] = addresses[0][4][0]
            except (OSError,KeyError):
                pass
        try:
            self.raw = psycopg.connect(url, autocommit=True, prepare_threshold=None,
                                       connect_timeout=10, row_factory=row_factory, **options)
        except psycopg.OperationalError as exc:
            message = str(exc).lower()
            logging.error('UCP database unavailable: tls_certificate=%s authentication=%s network=%s ipv4_selected=%s',
                          'certificate' in message, 'authentication' in message or 'password' in message,
                          'connection' in message or 'timeout' in message, bool(options))
            # Keep one useful diagnostic after redacting credentials and URLs.
            info = psycopg.conninfo.conninfo_to_dict(url)
            diagnostic = str(exc).splitlines()[0]
            from urllib.parse import quote
            for key in ('password','user','dbname'):
                value = info.get(key,'')
                if value:
                    diagnostic = diagnostic.replace(value,'[redacted]').replace(quote(value,safe=''),'[redacted]')
            diagnostic = re.sub(r'postgres(?:ql)?://\S+', '[redacted-dsn]', diagnostic)
            raise RuntimeError('PostgreSQL unavailable: '+diagnostic[:350]) from None
        self.raw.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(schema)))
        self.raw.execute("SET statement_timeout = '15s'")
        self.raw.execute("SET lock_timeout = '10s'")
        self.raw.execute("SET idle_in_transaction_session_timeout = '20s'")

    @property
    def in_transaction(self):
        return self.raw.info.transaction_status != TransactionStatus.IDLE

    def execute(self, query, params=()):
        q = query.strip().rstrip(';')
        pragma = re.fullmatch(r'PRAGMA table_info\((\w+)\)', q, re.I)
        if pragma:
            return self._run('SELECT column_name AS name FROM information_schema.columns '
                             'WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position',
                             (self.schema, pragma[1]))
        if q.upper().startswith('PRAGMA '):
            return Result()
        if q.upper() in ('BEGIN', 'BEGIN IMMEDIATE'):
            self.raw.execute('BEGIN' if q.upper() == 'BEGIN IMMEDIATE' else
                             'BEGIN ISOLATION LEVEL REPEATABLE READ')
            if q.upper() == 'BEGIN IMMEDIATE':
                # Keep the lab's serialized write invariant across server instances.
                self.raw.execute('SELECT pg_advisory_xact_lock(hashtext(%s))', (self.schema,))
            return Result()
        q = translate(q)
        insert = re.match(r'INSERT INTO (\w+)\b', q, re.I)
        identity = bool(insert and insert[1].lower() in IDENTITY_TABLES)
        if identity:
            q += ' RETURNING id'
        result = self._run(q, params)
        if identity and result.rows:
            result.lastrowid = result.rows[0]['id']
        return result

    def _run(self, query, params=()):
        # sqlite constraint errors don't abort a transaction; preserve that contract.
        savepoint = self.in_transaction and query.upper() not in ('COMMIT', 'ROLLBACK')
        if savepoint:
            self.raw.execute('SAVEPOINT ucp_statement')
        try:
            cur = self.raw.execute(query, params or None)
            result = Result(cur.fetchall() if cur.description else (), cur.rowcount)
            if savepoint:
                self.raw.execute('RELEASE SAVEPOINT ucp_statement')
            return result
        except psycopg.IntegrityError as cause:
            if savepoint:
                self.raw.execute('ROLLBACK TO SAVEPOINT ucp_statement')
                self.raw.execute('RELEASE SAVEPOINT ucp_statement')
            error = sqlite3.IntegrityError('Database constraint violation')
            error.sqlite_errorcode = (sqlite3.SQLITE_CONSTRAINT_UNIQUE
                                      if cause.sqlstate == '23505' else sqlite3.SQLITE_CONSTRAINT)
            raise error from None

    def executescript(self, script):
        # UCP schema scripts contain no SQL functions or semicolons in literals.
        for query in script.split(';'):
            if query.strip():
                self.execute(query)

    def commit(self):
        self.raw.commit()
    def rollback(self):
        self.raw.rollback()
    def close(self):
        self.raw.close()


@contextmanager
def initialize_schema(url, schema):
    """Serialize additive initialization, including parallel cold starts."""
    conn = Connection(url, schema)
    try:
        conn.raw.execute('SELECT pg_advisory_lock(hashtext(%s))', (schema + '_migration',))
        conn.raw.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
        conn.raw.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM PUBLIC').format(sql.Identifier(schema)))
        # No API role receives privileges. Auth remains in FastAPI.
        yield
        tables = conn.raw.execute('SELECT tablename FROM pg_tables WHERE schemaname=%s', (schema,)).fetchall()
        for row in tables:
            conn.raw.execute(sql.SQL('ALTER TABLE {}.{} ENABLE ROW LEVEL SECURITY').format(
                sql.Identifier(schema), sql.Identifier(row['tablename'])))
    finally:
        # Closing a session releases its advisory lock even if initialization fails.
        conn.close()
